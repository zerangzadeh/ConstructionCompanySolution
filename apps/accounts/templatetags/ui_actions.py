@register.filter
def form_action_label(title: str) -> str:
    """Keep unfamiliar task titles intact instead of inferring their action."""
    return FORM_ACTION_LABELS.get(title, title)


@register.filter
def commercial_status_label(value: str, source: str) -> str:
    """Use the source model's labels without changing the review projection."""
    from apps.billing.models import PayableCertificate, ProgressClaim
    from apps.contracts.models import ContractualRecord

    model = {
        "صورت‌وضعیت دریافتنی": ProgressClaim,
        "گواهی پرداخت پیمان جزء": PayableCertificate,
    }.get(source, ContractualRecord)
    return dict(model._meta.get_field("status").choices).get(value, value)
